def get_trPL(data_trPL, trPL_lyr):
    ''' Process the output of the tj file to extract the trPL data for the specified layer, taking into account the blocking layers and the layer indexing.

    Parameters
    ----------
    data_trPL : DataFrame
        The data from the tj file, which contains the time (t) and the current density (Jdir) for each layer 
    trPL_lyr : int
        The index of the layer to calculate the trPL for, starting from 1 for the first layer of the simulation setup with blocking layers 
    
    Returns
    -------
    DataFrame
        A DataFrame containing the time (t) and the trPL signal (trPL) for the specified layer, where trPL is equal to the current density (Jdir) for that layer. 
    '''

    # Only a single layer currently
    trPL = data_trPL[f'JdirL{trPL_lyr}'] # We use the direct recombination current density (Jdir) for the trPL signal.
    t = data_trPL['t']

    # save the trPL data to a file
    df_trPL = pd.DataFrame({'t': t, 'trPL': trPL})

    return df_trPL

def plot_trPL(session_path, output_file, xlim = None, ylim = None, xscale = 'log', yscale = 'log'):
    ''' Simple plot of the trPL data from the output file generated by the run_trPL_simu function. 
    The output file should contain two columns: time (t) and trPL signal (trPL). The function will create a plot of trPL vs time on a log-log scale.

    Parameters
    ----------
    session_path : string
        The path to the session folder, which is the working directory for the simulation
    output_file : string
        The name of the output file containing the trPL data, which should be located in the session path
    xlim : list, optional
        The limits for the x-axis, by default None, which means that the limits will be determined automatically based on the data
    ylim : list, optional
        The limits for the y-axis, by default None, which means that the limits will be determined automatically based on the data
    xscale : string, optional
        The scale for the x-axis, by default 'log'
    yscale : string, optional
        The scale for the y-axis, by default 'log'

    Returns
    -------
    None

    '''
    # simple trPL plot
    data_trPL = pd.read_csv(os.path.join(session_path, output_file),sep=r'\s+')
    t = data_trPL['t']*1E9 # Convert time to ns for plotting
    trPL = data_trPL['trPL']

    fig, ax = plt.subplots()
    ax.plot(t, trPL)
    ax.set_xlabel('Time [ns]')
    ax.set_ylabel(r'trPL | Jdir [Am$^{-2}$]')
    ax.set_title('Time Resolved Photoluminescence (trPL) Simulation')
    ax.set_xscale(xscale)
    ax.set_yscale(yscale)

    if xlim is not None:
        xlim = [x*1E9 for x in xlim]
        ax.set_xlim(xlim)
    if ylim is not None:
        ax.set_ylim(ylim)

    plt.tight_layout()
    plt.show()
    return

def run_trPL_simu(zimt_device_parameters, session_path, lyr_idx, t_max, t_scale, t_step, t_pulse, FWHM, genProfile='calc', spectrum_type = 'laser', I = 6E15, wavelength = 640E-9, G_ehp = 1E31, contactless_device = True, format_output=True, run_mode=False, tVG_name = 'tVG.txt', output_file = 'trPL.dat', tj_name = 'tj.dat', log_name = 'log.txt',varFile ='none', block_layer_file='Block.txt',**kwargs):
    """ Run a time resolved PhotoLuminescence (trPL) simulation, requiring the definition of a (Gaussian) light pulse.
    There is an option to use a contactless device architecture, which adds blocking layers to the simulation setup. 
    The output PL is given in terms of the equivalent direct recombination current (Jdir) of the layer specified by lyr_idx.

    Parameters
    ----------
    zimt_device_parameters : string
        The name of the ZimT device parameters file, which should be located in the session path
    session_path : string
        The path to the session folder, which is the working directory for the simulation
    lyr_idx : int
        The index of the active layer to calculate the trPL for, starting from 0 for the first layer of the original setup (i.e. without the blocking layers)
    t_max : float
        The maximum time for the experiment
    t_scale : string
        The time scale to use for the time array, which can be 'lin' for linear or 'log' for logarithmic
    t_step : float
        The time step
    t_pulse : float
        The center of the pulse in time. Make sure it is far enough from t=0 otherwise first part of pulse will be cut, resulting in lower number of photons
    FWHM : float
        The full width at half maximum (FWHM) of the pulse
    genProfile : string
        The type of generation profile to use, either 'calc', 'none', or 'userFile', by default 'calc'
    spectrum_type : string
        The type of spectrum to use, either 'spectrum' or 'laser', by default 'spectrum'
    I : float
        The intensity of the pulse in photons/m^2/pulse, only used if spectrum_type is 'laser', by default 1E15
    wavelength : float
        The wavelength of the pulse in meters, only used if spectrum_type is 'laser', by default 400E-9
    G_ehp : float, optional
        The generation rate in m^-3 s^-1, only used if genProfile is 'none', by default 1E31
    contactless_device : bool, optional
        Whether to use a contactless device architecture, which adds blocking layers to the simulation setup, by default True
    format_output : bool, optional
        Whether to format the output files to remove the blocking layers and update the layer indices back to their original values, by default True
    run_mode : bool, optional
        If False, show verbose output in console, by default False
    tVG_name : string, optional
        The name of the tVG file to create, by default 'tVG.txt'
    output_file : string, optional
        The name of the output file to create with the trPL data, by default 'trPL.dat'
    tj_name : string, optional
        The name of the tj file to create, by default 'tj.dat'
    log_name : string, optional
        The name of the log file to create, by default 'log.txt'
    varFile : string, optional
        The name of the var file to create, by default 'none'. If 'none', no var file will be created and the varFile parameter will not be passed to ZimT.
       
    Returns
    -------
    CompletedProcess
        Output object of with returncode and console output of the simulation
    string
        Return message to display on the UI, for both success and failed
    """
    verbose = kwargs.get('verbose', False) # Check if the user wants to see the console output
    UUID = kwargs.get('UUID', '') # Check if the user wants to add a UUID to the tj file name
    cmd_pars = kwargs.get('cmd_pars', None) # Check if the user wants to add additional command line parameters
    # Check if the user wants to force the use of thread safe mode, necessary for Windows with parallel simulations
    if os.name == 'nt':
        threadsafe = kwargs.get('threadsafe', True) # Check if the user wants to force the use of threads instead of processes
    else:
        threadsafe = kwargs.get('threadsafe', False) # Check if the user wants to force the use of threads instead of processes
    
    turnoff_autoTidy = kwargs.get('turnoff_autoTidy', None) # Check if the user wants to turn off the autoTidy function in SIMsalabim
    if turnoff_autoTidy is None: 
        if not threadsafe:
            turnoff_autoTidy = True
        else:
            turnoff_autoTidy = False

    # Update the file names with the UUID
    if UUID != '':
        dum_str = f'_{UUID}'
    else:
        dum_str = ''

    # Update the filenames with the UUID
    tj_name = os.path.join(session_path, tj_name)
    output_file = os.path.join(session_path, output_file)
    tVG_name = os.path.join(session_path, tVG_name)
    log_name = os.path.join(session_path, log_name)
    if UUID != '':
        tj_file_name_base, tj_file_name_ext = os.path.splitext(tj_name)
        tj_name = tj_file_name_base + dum_str + tj_file_name_ext 
        tVG_name_base, tVG_name_ext = os.path.splitext(tVG_name)
        tVG_name = tVG_name_base + dum_str + tVG_name_ext
        log_name_base, log_name_ext = os.path.splitext(log_name)
        log_name = log_name_base + dum_str + log_name_ext
        output_file_base, output_file_ext = os.path.splitext(output_file)
        output_file = output_file_base + dum_str + output_file_ext
        if varFile != 'none':
            var_file_base, var_file_ext = os.path.splitext(varFile)
            varFile = var_file_base + dum_str + var_file_ext
            varFile = os.path.join(session_path,varFile)

    # When not using a calculated or user-defined generation profile, the generation rate must be specified in the layer parameters file. 
    # Therefore, we add the generation rate to the command line parameters to update the layer parameters file accordingly.
    if genProfile == 'none': # Add the the generation rate to the arguments
        cmd_pars.append({'par': f'l{lyr_idx}.G_ehp', 'val': str(G_ehp)})

    # Add the blocking layers to the simulation setup if a contactless device architecture is used.
    if contactless_device:
        returncode, cmd_pars, block_layer_file = create_contactless_device(session_path, zimt_device_parameters, block_layer_file=block_layer_file, cmd_pars = cmd_pars)

    # Check if the layer index specified by the user makes sense given the original device architecture (taking into account blocking layers if defined)
    dev_pars,layers = load_device_parameters(session_path, zimt_device_parameters)
    if contactless_device and len(layers)-3 < lyr_idx: # Subtract 3 for the two blocking layers and the simulation setup
        msg = f'Layer index {lyr_idx} is out of bounds for the used device architecture. The device has only {len(layers)-3} layer(s).'
        return -1, msg
    elif len(layers)-1 < lyr_idx: # Subtract 1 for the simulation setup
        msg = f'Layer index {lyr_idx} is out of bounds for the used device architecture. The device has only {len(layers)-1} layer(s).'
        return -1, msg

    # Run the ZimT simulation for a (Gaussian) light pulse. The trPL signal is then calculated from the output.
    result, message = lp.run_light_pulse_simu(zimt_device_parameters, session_path, t_max, t_scale, t_step, t_pulse, FWHM, 
                                              genProfile, spectrum_type, I, wavelength, run_mode, tVG_name, tj_name, log_name, 
                                              varFile, cmd_pars, turnoff_autoTidy, verbose, threadsafe)

    if result == 0 or result == 95:
        # Check if the file exists first
        if not os.path.isfile(tj_name):
            msg = f'tj file not found: {tj_name}'
            return -1, msg
        
        data_trPL = pd.read_csv(os.path.join(session_path, tj_name),sep=r'\s+')

        # process the output to get the trPL data, this needs to take into account the blocking layers and also which layers should be taken into account for the signal
        if contactless_device:
            trPL_lyr = lyr_idx + 1
        else:
            trPL_lyr = lyr_idx

        # Calcuate the trPL signal for the specified layer
        df_trPL = get_trPL(data_trPL, trPL_lyr)
        df_trPL.to_csv(os.path.join(session_path,output_file), index=False, sep = ' ', float_format='%.3e') # Write to the output file

    # Format the output files to remove the blocking layers and update the layer indices back to their original values
    if contactless_device and format_output:
        process_output_contactless(session_path, zimt_device_parameters, 'zimt', format_output = format_output, clean_simulation_setup=False, tJ_file = tj_name, Var_file = varFile, block_layer_file = block_layer_file)

    return result, message

